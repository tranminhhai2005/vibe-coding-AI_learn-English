List<String> suggestSpelling(String input) {
  final word = input.trim().toLowerCase();
  if (word.length < 4 || _commonEnglishWords.contains(word)) return const [];
  final limit = word.length > 7 ? 2 : 1;
  return _commonEnglishWords
      .where((candidate) => editDistance(word, candidate) <= limit)
      .take(3)
      .toList();
}
